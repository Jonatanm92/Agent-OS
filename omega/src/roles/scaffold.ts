import type { CommitInfo } from '../core/vcs.ts';
import type { Mission } from '../core/types.ts';
import { getRole } from './registry.ts';
import { specToMarkdown } from './spec.ts';
import { writeProjectFile } from './files.ts';

/** Architect: deterministic project skeleton every mission shares. */
export function writeScaffold(mission: Mission): string[] {
  const spec = mission.spec;
  if (!spec) throw new Error('architect needs a spec');
  const policy = getRole('architect').policy;
  const root = mission.projectDir;
  const pkg = {
    name: spec.slug,
    version: '0.1.0',
    private: true,
    description: spec.summary,
    type: 'module',
    main: 'src/index.js',
    ...(spec.cli ? { bin: { [spec.slug]: 'src/cli.js' } } : {}),
    scripts: {
      test: 'node --test "test/**/*.test.js"',
      ...(spec.cli ? { start: 'node src/cli.js' } : {}),
    },
    engines: { node: '>=22' },
    license: 'UNLICENSED',
  };
  writeProjectFile(policy, root, 'package.json', JSON.stringify(pkg, null, 2) + '\n');
  writeProjectFile(policy, root, '.gitignore', 'node_modules/\n');
  writeProjectFile(
    policy,
    root,
    'OMEGA.md',
    `<!-- Generated by OMEGA mission ${mission.id}. This file is the contract the roles work against. -->\n\n${specToMarkdown(spec)}\n## Layout\n- \`src/\` — implementation (coder role only)\n- \`test/\` — acceptance tests (test-author role only)\n- \`README.md\` — documentation (docs role only)\n`,
  );
  writeProjectFile(policy, root, 'src/.gitkeep', '');
  writeProjectFile(policy, root, 'test/.gitkeep', '');
  return ['package.json', '.gitignore', 'OMEGA.md', 'src/.gitkeep', 'test/.gitkeep'];
}

/** Docs: README built only from verified facts (spec, OMEGA's own test run, scan, git log). */
export function writeReadme(mission: Mission, commits: CommitInfo[]): void {
  const spec = mission.spec;
  if (!spec) throw new Error('docs needs a spec');
  const t = mission.tests;
  const sec = mission.security;
  const lines: string[] = [`# ${spec.title}`, '', spec.summary, ''];
  lines.push('## Usage', '', '```js', `import { ${spec.module.exports.map((e) => e.name).join(', ')} } from './src/index.js';`, '```', '');
  for (const e of spec.module.exports) lines.push(`- \`${e.name}\` \`${e.signature}\` — ${e.description}`);
  if (spec.cli) {
    lines.push('', '### Command line', '', '```sh', spec.cli.usage, ...spec.cli.examples, '```');
  }
  lines.push('', '## Run the tests', '', '```sh', 'npm test', '```', '', 'Requires Node.js 22+. No dependencies.', '');
  lines.push('## Acceptance criteria and verified status', '');
  lines.push('| Id | Criterion | Status |', '|----|-----------|--------|');
  for (const ac of spec.acceptanceCriteria) {
    const cov = t?.coverage.find((c) => c.id === ac.id);
    const status = !cov ? 'not run' : cov.passing ? 'pass' : cov.covered ? 'FAIL' : 'not covered';
    lines.push(`| ${ac.id} | ${ac.text.replace(/\|/g, '\\|')} | ${status} |`);
  }
  if (t) lines.push('', `Independent test run #${t.runId} by OMEGA: ${t.pass}/${t.tests} passed, exit code ${t.exitCode}.`);
  if (sec) lines.push('', `Security scan: ${sec.high} high, ${sec.medium} medium, ${sec.findings.length} findings in total.`);
  if (spec.outOfScope.length) lines.push('', '## Not included in this version', '', ...spec.outOfScope.map((o) => `- ${o}`));
  lines.push('', '## Provenance', '', `Built by OMEGA mission \`${mission.id}\` (engine: ${mission.engine}${mission.engine === 'claude-code' ? `, model: ${mission.model}` : ''}).`, '');
  for (const c of [...commits].reverse()) lines.push(`- \`${c.sha.slice(0, 10)}\` ${c.author}: ${c.subject}`);
  lines.push('', 'Generated documentation — review before publishing.', '');
  writeProjectFile(getRole('docs').policy, mission.projectDir, 'README.md', lines.join('\n'));
}
